const english = new Map(Object.entries(vietnamese).map(([key, value]) => [value, key]));

const dynamicVietnamese = [
  [/^(\d+) (?:group )?chats · (\d+) (?:people|agents in the agent library)$/, (_, chats, people) => `${chats} cuộc trò chuyện · ${people} nhân vật`],
  [/^Members (\d+)$/, (_, count) => `Thành viên ${count}`],
  [/^(\d+) (people|agents|roles|members|messages)$/, (_, count, unit) => `${count} ${{ people: 'nhân vật', agents: 'nhân vật', roles: 'vai trò', members: 'thành viên', messages: 'tin nhắn' }[unit]}`],
  [/^Read (\d+) messages?$/, (_, count) => `Đã đọc ${count} tin nhắn`],
  [/^Edit person: (.+)$/, (_, name) => `Chỉnh nhân vật: ${name}`],
  [/^Default model: (.+)$/, (_, name) => `Mô hình mặc định: ${name}`],
  [/^For: (.+)$/, (_, name) => `Dùng cho: ${name}`],
  [/^Step (\d+)$/, (_, count) => `Bước ${count}`],
  [/^(.+) mode · (\d+) members · (\d+) messages$/, (_, mode, count, messages) => `${localizeUI(mode + ' mode', 'vi')} · ${count} thành viên · ${messages} tin nhắn`],
  [/^(\d+) (?:people|agents) · Current: (.+)$/, (_, count, name) => `${count} thành viên · Đang chọn: ${name}`],
  [/^No matching (built-in|custom) people$/, (_, kind) => `Không tìm thấy nhân vật ${kind === 'custom' ? 'tùy chỉnh' : 'có sẵn'} phù hợp`],
  [/^No (built-in|custom) people yet$/, (_, kind) => `Chưa có nhân vật ${kind === 'custom' ? 'tùy chỉnh' : 'có sẵn'}`],
  [/^Replying: (.+)$/, (_, names) => `Đang trả lời: ${names}`],
  [/^Will send to: (.+)$/, (_, names) => `Sẽ gửi cho: ${names}`],
  [/^Port (\d+), local connections only\. When enabled, local tools can create group chats and send tasks\.$/, (_, port) => `Cổng ${port}, chỉ nhận kết nối cục bộ. Khi bật, công cụ trên máy có thể tạo cuộc trò chuyện nhóm và gửi nhiệm vụ.`],
  [/^Port (\d+); local connections only\.$/, (_, port) => `Cổng ${port}. Chỉ cho phép kết nối cục bộ.`],
  [/^(.+) send button is unavailable\. Try again shortly\.$/, (_, site) => `Nút gửi của ${site} chưa khả dụng. Hãy thử lại sau.`],
];

export function localizeUI(value, language) {
  const source = english.get(value) ?? value;
  if (language === 'en') return source;
  if (Object.hasOwn(vietnamese, source)) return vietnamese[source];

  for (const [pattern, translate] of dynamicVietnamese) {
    const match = source.match(pattern);
    if (match) return translate(...match);
  }
  if (source.includes(' · ')) return source.split(' · ').map(part => localizeUI(part, language)).join(' · ');
  return source;
}
